package com.veersetu.khandesh;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;

/**
 * VeerSetu Khandesh
 * -----------------
 * "Setu" (सेतु) means bridge. This application is the bridge between the
 * families of soldiers who were martyred while serving in the Indian Armed
 * Forces from the Khandesh region (Dhule, Jalgaon, Nandurbar, Nashik) and
 * citizens who wish to support them financially or otherwise.
 */
@SpringBootApplication
public class VeerSetuApplication {

    public static void main(String[] args) {
        SpringApplication.run(VeerSetuApplication.class, args);
    }
}
